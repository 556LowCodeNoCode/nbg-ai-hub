def write_csv(name, header, rows):
    with open(os.path.join(CSVDIR, name + '.csv'), 'w', newline='', encoding='utf-8-sig') as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    print('%-26s %d γραμμές' % (name, len(rows)))


